//Object (Objetos)
// Um objeto agrupa várias informações dentro de uma mesma váriavel, usando chave e valor

let pessoa = {
    nome: "João",
    idade: 16,
    cidade: "guarulhos"
};

console.log(pessoa.nome);
console.log(pessoa.idade);
console.log(pessoa.cidade);


